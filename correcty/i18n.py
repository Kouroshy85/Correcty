_UPPER_WORDS = {"url": "URL", "id": "ID", "sms": "SMS", "pdf": "PDF"}
_ASCII_NAME = re.compile(r"[A-Za-z0-9_]+")
_DIGITS_FA = str.maketrans("0123456789", "۰۱۲۳۴۵۶۷۸۹")


def normalize_language(code: str | None) -> str:
    return code if code in LANGUAGES else DEFAULT_LANGUAGE


def direction(lang: str) -> str:
    return "rtl" if lang in RTL_LANGUAGES else "ltr"


def format_number(n: int, lang: str) -> str:
    text = f"{n:,}" if lang == "en" else str(n)
    return text.translate(_DIGITS_FA) if lang == "fa" else text


def _fill(text: str, params: dict) -> str:
    return re.sub(r"\{(\w+)\}", lambda m: str(params[m.group(1)]) if m.group(1) in params else m.group(0), text)


def translate(key: str, lang: str, **params) -> str:
    table = STRINGS.get(lang, STRINGS[DEFAULT_LANGUAGE])
    text = table.get(key) or STRINGS[DEFAULT_LANGUAGE].get(key, key)
    return _fill(text, params) if params else text


def plural(base: str, n: int, lang: str, **params) -> str:
    key = f"{base}_one" if n == 1 else f"{base}_other"
    return translate(key, lang, n=format_number(n, lang), **params)


def error_message(code: str, params: dict | None, lang: str) -> str:
    params = dict(params or {})
    if "max" in params and isinstance(params["max"], int):
        params["max"] = format_number(params["max"], lang)
    if "min" in params and isinstance(params["min"], int):
        params["min"] = format_number(params["min"], lang)
    key = f"err_{code}"
    if key not in STRINGS[DEFAULT_LANGUAGE]:
        key = "err_invalid_type"
    return translate(key, lang, **params)


def _split_words(name: str) -> list[str]:
    spaced = re.sub(r"(?<=[a-z0-9])(?=[A-Z])", "_", name)
    return [w for w in re.split(r"[_\-]+", spaced) if w]


def auto_label(name: str, lang: str = DEFAULT_LANGUAGE) -> str:
    """Readable label for a variable name: ``user_name`` -> "User name" / "نام کاربر"."""
    words = _split_words(name)
    if not words:
        return name
    if lang == "fa" and _ASCII_NAME.fullmatch(name):
        lowered = [w.lower() for w in words]
        if all(w in LABEL_WORDS_FA for w in lowered):
            return " ".join(LABEL_WORDS_FA[w] for w in reversed(lowered))
    if not _ASCII_NAME.fullmatch(name):
        return " ".join(words)
    pretty = [_UPPER_WORDS.get(w.lower(), w.lower()) for w in words]
    first = pretty[0]
    pretty[0] = first if first in _UPPER_WORDS.values() else first[:1].upper() + first[1:]
    return " ".join(pretty)


def client_payload(lang: str) -> dict:
    """Everything the browser needs to speak the current language."""
    return {
        "lang": lang,
        "dir": direction(lang),
        "strings": STRINGS[lang],
        "labelWords": LABEL_WORDS_FA if lang == "fa" else {},
        "upperWords": _UPPER_WORDS,
    }
